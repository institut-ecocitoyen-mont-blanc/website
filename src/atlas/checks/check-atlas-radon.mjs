import { createRequire } from "node:module";
import assert from "node:assert/strict";
const { chromium } = createRequire(import.meta.url)("playwright");
const browser = await chromium.launch({ headless: true, channel: "chrome" });
const atlasUrl = process.env.ATLAS_URL || "http://localhost:3000/atlas";
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  // The bundled reference must work even when the published-data service is down.
  await page.route("**/iec-atlas-data/**", route => route.abort());
  const errors = [], upstream = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (/georisques\.gouv\.fr/.test(request.url())) upstream.push(request.url()); });
  await page.goto(atlasUrl);
  await page.locator(".leaflet-container").waitFor();
  const toggle = page.getByRole("checkbox", { name: "Potentiel radon", exact: true });
  assert.equal(await toggle.isChecked(), false);
  assert.equal(await page.getByRole("checkbox", { checked: true }).count(), 1);
  await page.getByRole("checkbox", { name: "Sources de pollution potentielle", exact: true }).uncheck();
  await toggle.check();
  const polygons = page.locator(".leaflet-radon-pane path");
  await page.waitForFunction(() => document.querySelectorAll(".leaflet-radon-pane path").length === 10);
  assert.deepEqual(await polygons.evaluateAll(paths => paths.reduce((counts, path) => {
    const color = path.getAttribute("fill"); counts[color] = (counts[color] || 0) + 1; return counts;
  }, {})), { "#fef0b5": 7, "#f9ad55": 1, "#c65328": 2 });
  assert.match(await page.locator("#atlas-layer-group-soil").innerText(), /1 active/);
  assert.equal(await page.getByLabel("Légende du potentiel radon").locator("li").count(), 3);
  const slider = page.getByRole("slider", { name: "Opacité · Potentiel radon", exact: true });
  await slider.focus(); await slider.press("Home"); await slider.press("ArrowRight");
  assert.equal(await slider.inputValue(), "0.2");
  assert.ok((await polygons.evaluateAll(paths => paths.map(path => path.getAttribute("fill-opacity")))).every(value => value === "0.2"));
  await slider.press("End");
  // Passy is the seventh commune in the pinned, reproducible boundary order.
  await polygons.nth(6).dispatchEvent("click");
  let dialog = page.getByRole("dialog");
  await dialog.waitFor();
  assert.match(await dialog.innerText(), /Passy/);
  assert.match(await dialog.innerText(), /Catégorie 3 sur 3/);
  assert.match(await dialog.innerText(), /Non mesurée dans cette couche/);
  assert.equal(await dialog.getByRole("link", { name: "Données communales · Géorisques", exact: true }).getAttribute("href"), "https://www.georisques.gouv.fr/api/v1/radon?code_insee=74208");
  assert.equal(new URL(page.url()).searchParams.get("pin"), "radon:74208");
  await page.keyboard.press("Escape");
  assert.equal(await dialog.count(), 0);
  await page.goBack(); await dialog.waitFor();
  await page.getByRole("button", { name: "Fermer la fiche", exact: true }).click();
  await page.getByText("Consulter les 10 communes", { exact: true }).click();
  await page.getByRole("button", { name: /^Les Contamines-Montjoie ·/ }).click();
  assert.match(await dialog.innerText(), /Catégorie 2 sur 3/);
  await page.getByRole("button", { name: "Fermer la fiche", exact: true }).click();
  await page.locator(".leaflet-container").screenshot({ path: "/tmp/atlas-radon-map.png" });
  await toggle.uncheck();
  assert.equal(await page.locator(".leaflet-radon-pane").count(), 0);
  const direct = new URL(atlasUrl); direct.search = "layers=&pin=radon:74208";
  await page.goto(direct.href);
  await page.getByRole("dialog").waitFor();
  assert.equal(await page.getByRole("checkbox", { name: "Potentiel radon", exact: true }).isChecked(), true);
  assert.match(await page.getByRole("dialog").innerText(), /Catégorie 3 sur 3/);
  await page.getByRole("dialog").screenshot({ path: "/tmp/atlas-radon-details.png" });
  await page.getByRole("button", { name: "Fermer la fiche", exact: true }).click();
  await page.setViewportSize({ width: 375, height: 812 });
  await page.getByRole("button", { name: "Couches 1", exact: true }).click();
  await page.getByText("Consulter les 10 communes", { exact: true }).click();
  await page.getByRole("button", { name: /^Combloux ·/ }).click();
  dialog = page.getByRole("dialog").filter({ has: page.getByRole("heading", { name: "Combloux", exact: true }) });
  await dialog.waitFor();
  assert.match(await dialog.innerText(), /Catégorie 1 sur 3/);
  assert.ok(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth));
  await dialog.screenshot({ path: "/tmp/atlas-radon-mobile.png" });
  await page.getByRole("button", { name: "Fermer la fiche", exact: true }).click();
  await page.getByRole("checkbox", { name: "Potentiel radon", exact: true }).uncheck();
  await page.getByRole("button", { name: "Voir la carte", exact: true }).click();
  await page.getByRole("button", { name: "Couches 0", exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  assert.deepEqual(upstream, [], "Radon never requests the provider from visitors’ browsers");
  console.log("PASS: ten radon polygons, exact categories, opacity, commune details, URL history/reload, mobile and offline availability");
} finally { await browser.close(); }
